"""Maintainer-only, pixel-exact packing. Python 3 + Pillow 11.0.0; no build dependency.

Run after importing/exporting coast PNGs. Originals, their hashes and anchors remain
authoritative. The browser only decodes these checked-in lossless WebP sheets.
"""
from pathlib import Path
from PIL import Image
from PIL import __version__ as pillow_version
from io import BytesIO
import hashlib
import json
import math

root = Path(__file__).resolve().parent.parent
assert pillow_version == '11.0.0', 'Use the pinned Pillow 11.0.0 encoder for reproducible packed art'
coast = json.loads((root / 'assets/coast/manifest.json').read_text(encoding='utf-8'))
assets = coast['assets']
assert len({a['id'] for a in assets}) == len(assets)
groups = {'legacy': [a for a in assets if '/enemy-v1/' not in a['file']]}
for a in assets:
    if '/enemy-v1/' in a['file']:
        groups.setdefault(a['kind'], []).append(a)
packed = {'schema': 1, 'encoding': 'lossless WebP, exact RGBA, Pillow 11.0.0', 'sheets': [], 'frames': []}
output = root / 'assets/coast/packed'
output.mkdir(exist_ok=True)
sha = lambda data: hashlib.sha256(data).hexdigest()
for name, frames in groups.items():
    body = name != 'legacy'
    if body:
        assert len(frames) == 26 and all((a['w'], a['h']) == (32, 48) for a in frames[:25])
        assert (frames[25]['w'], frames[25]['h']) == (48, 32)
        sheet = Image.new('RGBA', (160, 272))
        positions = [(i % 5 * 32, i // 5 * 48) if i < 25 else (0, 240) for i in range(26)]
    else:
        w, h = max(a['w'] for a in frames), max(a['h'] for a in frames)
        sheet = Image.new('RGBA', (w * 8, h * math.ceil(len(frames) / 8)))
        positions = [(i % 8 * w, i // 8 * h) for i in range(len(frames))]
    originals = []
    for a, (x, y) in zip(frames, positions):
        data = (root / a['file']).read_bytes()
        assert sha(data) == a['sha256'], a['file']
        image = Image.open(BytesIO(data)).convert('RGBA')
        assert image.size == (a['w'], a['h'])
        sheet.paste(image, (x, y))  # No alpha mask: copy every channel, including transparent pixels.
        originals.append(image)
    data = BytesIO()
    sheet.save(data, format='WEBP', lossless=True, exact=True, method=6, quality=100)
    encoded = data.getvalue()
    decoded = Image.open(BytesIO(encoded)).convert('RGBA')
    file = f'assets/coast/packed/{name}.webp'
    for a, image, (x, y) in zip(frames, originals, positions):
        assert decoded.crop((x, y, x + a['w'], y + a['h'])).tobytes() == image.tobytes(), a['id']
        packed['frames'].append({'id': a['id'], 'sourceSha256': a['sha256'], 'sheet': file,
                                 'x': x, 'y': y, 'w': a['w'], 'h': a['h']})
    (root / file).write_bytes(encoded)
    packed['sheets'].append({'file': file, 'sha256': sha(encoded), 'bytes': len(encoded),
                             'w': sheet.width, 'h': sheet.height})
(output / 'manifest.json').write_text(json.dumps(packed, indent=2) + '\n', encoding='utf-8')
variables = {s['file']: f'sheet{i}' for i, s in enumerate(packed['sheets'])}
imports = '\n'.join(f"import {var} from '../../{file}';" for file, var in variables.items())
entries = '\n'.join(f"  ['{a['id']}', {variables[a['sheet']]}, {a['x']}, {a['y']}, {a['w']}, {a['h']}]," for a in packed['frames'])
source = """/** Pixel-exact coast sheets; generated by scripts/pack-coast-art.py. */
IMPORTS

const frames: readonly (readonly [string, string, number, number, number, number])[] = [
ENTRIES
];

let loaded: Promise<Map<string, HTMLCanvasElement>> | null = null;
/** Decode each sheet once, then restore the original frame canvases and anchors.
 * A failed cold load clears the complete candidate so an ordinary retry decodes again. */
export function loadCoastAssets(): Promise<Map<string, HTMLCanvasElement>> {
  loaded ??= (async () => {
    const images = new Map(await Promise.all([...new Set(frames.map(f => f[1]))].map(url =>
      new Promise<[string, HTMLImageElement]>((resolve, reject) => {
        const img = new Image(); img.onload = () => resolve([url, img]);
        img.onerror = () => reject(new Error('Coast sheet failed to decode')); img.src = url;
      }))));
    const result = new Map<string, HTMLCanvasElement>();
    for (const [id, url, x, y, w, h] of frames) {
      const canvas = document.createElement('canvas'); canvas.width = w; canvas.height = h;
      const g = canvas.getContext('2d'); if (!g) throw new Error('Canvas 2D unavailable');
      try { g.drawImage(images.get(url)!, x, y, w, h, 0, 0, w, h); }
      catch (error) { throw new Error(`Coast asset failed to prepare: ${id}`, { cause: error }); }
      result.set(id, canvas);
    }
    return result;
  })().catch(error => { loaded = null; throw error; });
  return loaded;
}
""".replace('IMPORTS', imports).replace('ENTRIES', entries)
(root / 'src/coast-view/assets.ts').write_text(source, encoding='utf-8')
print(f"Packed {len(assets)} unchanged frames into {len(groups)} sheets, {sum(s['bytes'] for s in packed['sheets'])} bytes")
